/**
 * Headline card rules test.
 *
 * Guards the four promises the headline cards make to a reader:
 *   1. the publisher and the feed's own title are always shown (never a rewritten title);
 *   2. the timestamp is WAT and honest — a missing feed timestamp says so instead of guessing;
 *   3. "Read original" only ever points at a real http(s) publisher link;
 *   4. the optional context line appears only for a rule we actually have, and every rule href is a
 *      route this site really serves (so a context line can never become a broken internal link).
 *
 * It also checks the two headline surfaces still share one card component, which is what keeps the
 * homepage briefing and the monitored-headlines list from drifting apart again.
 *
 * Run with: npm run headline:test
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {
  HEADLINE_CONTEXT_RULES,
  HEADLINE_LINK_UNAVAILABLE,
  HEADLINE_SOURCE_UNAVAILABLE,
  HEADLINE_TIME_UNAVAILABLE,
  headlineCardModel,
  headlineContext,
  headlineIsGoogleNews,
  headlineLinkHost,
  headlineSource,
  headlineTime,
  isExternalHeadlineLink,
} from "./headlines";

const ROOT = process.cwd();

/* ---------- route existence guard ---------- */

/** Routes generated by scripts/generate-content.ts (committed to the repo). */
function generatedRoutes(): Set<string> {
  const file = path.join(ROOT, "content/generated/articles.json");
  const raw = JSON.parse(fs.readFileSync(file, "utf8"));
  const articles = Array.isArray(raw) ? raw : raw.articles ?? [];
  return new Set(articles.map((a: { path: string }) => a.path.replace(/\/$/, "") || "/"));
}

/** Static App Router pages, resolved from app/**\/page.tsx. Dynamic segments are skipped. */
function staticRoutes(): Set<string> {
  const appDir = path.join(ROOT, "app");
  const out = new Set<string>();
  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      if (entry.name !== "page.tsx" && entry.name !== "page.ts" && entry.name !== "route.ts") continue;
      const rel = path.relative(appDir, dir).split(path.sep).filter(Boolean);
      if (rel.some((seg) => seg.startsWith("[") || seg.startsWith("("))) continue;
      out.add("/" + rel.join("/"));
    }
  };
  walk(appDir);
  return out;
}

function routeExists(href: string): boolean {
  const clean = href.replace(/\/$/, "") || "/";
  return staticRoutes().has(clean) || generatedRoutes().has(clean);
}

/* ---------- 1. context rules ---------- */

function run(): void {
  // FX / CBN / dollar / naira stories point at our own parallel-vs-CBN status page.
  for (const title of [
    "Dollar to Naira exchange rate today, October 14, 2026",
    "CBN clears $1.2bn FX backlog as naira firms at official window",
    "Black market dollar rate falls in Lagos",
  ]) {
    const context = headlineContext({ title });
    assert.equal(context?.href, "/status", `FX headline should point at /status: ${title}`);
  }

  // Petrol / diesel / depot stories point at the depot median page.
  for (const title of [
    "Petrol: Marketers hike pump price in Abuja, Lagos by N29/litre",
    "Dangote refinery cuts diesel (AGO) gantry price",
    "Fuel queues return in Port Harcourt as depot owners raise rates",
  ]) {
    const context = headlineContext({ title });
    assert.equal(context?.href, "/prices/fuel", `fuel headline should point at /prices/fuel: ${title}`);
  }

  // Passport / immigration, driver's licence and NIN headlines point at the GovHowTo guides we hold.
  assert.equal(
    headlineContext({ title: "International passport price in Nigeria: Immigration service announce increment" })?.href,
    "/howto/passport-renewal-2026",
  );
  assert.equal(
    headlineContext({ title: "FRSC to begin nationwide driver's licence verification exercise" })?.href,
    "/howto/drivers-licence-frsc",
  );
  assert.equal(headlineContext({ title: "NIMC opens NIN modification centres in 12 states" })?.href, "/howto/nin-correction");

  // Everything else stays silent: no generic filler line, ever.
  for (const title of [
    "Full list: Nigerian universities and cut-off marks for 2026 admission",
    "2026 data plans and prices for MTN, Airtel, Glo and T2mobile",
    "Consumers Pay More As Prices Of Eggs, Beans, Local Rice, Others Rise",
    "Super Eagles name squad for AFCON qualifier",
  ]) {
    assert.equal(
      headlineContext({ title }),
      null,
      `unrelated headline must not get a context line: ${title}`,
    );
  }

  // Blank title/context input must never produce a context line.
  assert.equal(headlineContext({ title: "" }), null);
  assert.equal(headlineContext({ title: "", topic: "" }), null);

  // One line only: the return type is a single object, never a list.
  const single = headlineContext({ title: "Petrol price rises as naira weakens further" });
  assert.ok(single && !Array.isArray(single), "at most one context line per headline");
  assert.equal(single.href, "/status", "the first matching rule wins, in a fixed order");

  // Every context href is an internal route that really renders — no external, no 404.
  for (const rule of HEADLINE_CONTEXT_RULES) {
    assert.ok(rule.href.startsWith("/"), `context href must be internal: ${rule.href}`);
    assert.ok(!rule.href.startsWith("//"), `context href must not be protocol-relative: ${rule.href}`);
    assert.ok(routeExists(rule.href), `context href must resolve to a real route: ${rule.href}`);
    assert.ok(rule.label.trim().length > 0 && rule.label.length <= 64, `context labels stay short: ${rule.label}`);
    assert.ok(!/\blive\b/i.test(rule.label), `context copy must never promise a "live" figure: ${rule.label}`);
  }
  // No two rules may claim the same destination with different copy.
  assert.equal(
    new Set(HEADLINE_CONTEXT_RULES.map((r) => r.id)).size,
    HEADLINE_CONTEXT_RULES.length,
    "context rule ids are unique",
  );

  /* ---------- 2. timestamps ---------- */

  // 18:43 UTC is 19:43 WAT on the same date: Nigeria is UTC+1 all year.
  assert.deepEqual(headlineTime("2026-10-11T18:43:31.000Z"), {
    label: "11 Oct 2026, 7:43 pm WAT",
    iso: "2026-10-11T18:43:31.000Z",
  });
  // A 23:30 UTC timestamp rolls into the next day in Lagos.
  assert.equal(headlineTime("2026-10-11T23:30:00.000Z").label, "12 Oct 2026, 12:30 am WAT");

  // Missing, blank, null and garbage timestamps are stated honestly, never invented.
  for (const missing of [undefined, null, "", "   ", "not a date", "Loading..."]) {
    const result = headlineTime(missing);
    assert.equal(result.label, HEADLINE_TIME_UNAVAILABLE, `honest fallback for ${JSON.stringify(missing)}`);
    assert.equal(result.iso, null, `no <time dateTime> for ${JSON.stringify(missing)}`);
  }

  /* ---------- 3. publisher + outbound link safety ---------- */

  assert.equal(headlineSource("Vanguard News"), "Vanguard News");
  assert.equal(headlineSource("  Channels Television  "), "Channels Television");
  assert.equal(headlineSource(""), HEADLINE_SOURCE_UNAVAILABLE);
  assert.equal(headlineSource(null), HEADLINE_SOURCE_UNAVAILABLE);
  assert.equal(headlineSource(undefined), HEADLINE_SOURCE_UNAVAILABLE);

  assert.equal(isExternalHeadlineLink("https://punchng.com/story"), true);
  assert.equal(isExternalHeadlineLink("http://punchng.com/story"), true);
  for (const unsafe of ["javascript:alert(1)", "data:text/html;base64,PHNjcmlwdD4=", "/status", "#", "", null, undefined, "not a url"]) {
    assert.equal(isExternalHeadlineLink(unsafe as string | null | undefined), false, `rejected link: ${String(unsafe)}`);
  }

  assert.equal(headlineLinkHost("https://www.punchng.com/story"), "punchng.com", "www. is stripped for display");
  assert.equal(headlineLinkHost("javascript:alert(1)"), null);

  const googleNewsLink =
    "https://news.google.com/rss/articles/CBMingFBVV95cUxQakpHZE51c1lNTDhudUs1WlpWZjRJMnM1elZPeVZ2aEhwN1RVWVQ3?oc=5";
  assert.equal(headlineIsGoogleNews(googleNewsLink), true, "our RSS items are Google News article links");
  assert.equal(headlineIsGoogleNews("https://punchng.com/story"), false);

  /* ---------- 4. card model over the live feed file ---------- */

  const feeds = JSON.parse(fs.readFileSync(path.join(ROOT, "data/live/feeds.json"), "utf8"));
  const topics = (feeds.topics ?? []) as { label: string; items: { title: string; link: string; source: string; published: string }[] }[];
  let checked = 0;
  let withContext = 0;
  for (const topic of topics) {
    for (const item of topic.items ?? []) {
      const model = headlineCardModel({ ...item, topic: topic.label });
      checked += 1;
      assert.ok(model.title.length > 0, "every card shows the feed's own title");
      assert.ok(model.source.length > 0, "every card names a publisher");
      assert.ok(
        model.time.iso !== null || model.time.label === HEADLINE_TIME_UNAVAILABLE,
        "every card either carries a real WAT time or says the feed gave none",
      );
      if (model.context) {
        withContext += 1;
        assert.ok(routeExists(model.context.href), `context href exists in the built site: ${model.context.href}`);
      }
      assert.ok(
        model.externalLink === null || model.externalLink.startsWith("http"),
        "the outbound action is either a real http(s) link or absent",
      );
    }
  }
  assert.ok(checked > 0, "the committed feed snapshot has headlines to check");
  assert.ok(withContext < checked, "not every headline gets a context line — silence is the default");

  /* ---------- 5. both surfaces share one card ---------- */

  const surface = (file: string) => fs.readFileSync(path.join(ROOT, file), "utf8");
  const newsFeed = surface("components/live/news-feed.tsx");
  const briefing = surface("components/live/daily-briefing.tsx");
  for (const [name, source] of [
    ["components/live/news-feed.tsx", newsFeed],
    ["components/live/daily-briefing.tsx", briefing],
  ] as const) {
    assert.match(source, /HeadlineList|HeadlineCard/, `${name} must render the shared headline card`);
    assert.doesNotMatch(source, /<a\s+href=\{item\.link\}/, `${name} must not hand-roll its own outbound anchor`);
  }

  const card = surface("components/live/headline-card.tsx");
  assert.match(card, /target="_blank"/, "outbound action opens in a new tab");
  assert.match(card, /rel="noopener noreferrer/, "outbound action is rel-guarded");
  assert.match(card, /Read original/, "the primary action is labelled Read original");
  assert.match(card, /<Link\s+href=\{model\.context\.href\}/, "context line uses an internal Next link");
  assert.doesNotMatch(card, /dangerouslySetInnerHTML/, "no raw HTML injection in headline cards");

  // The homepage and the feed list must not fetch or store third-party article text.
  for (const [name, source] of [
    ["components/live/news-feed.tsx", newsFeed],
    ["components/live/daily-briefing.tsx", briefing],
    ["components/live/headline-card.tsx", card],
    ["lib/headlines.ts", surface("lib/headlines.ts")],
  ] as const) {
    assert.doesNotMatch(source, /\bfetch\s*\(/, `${name} must not fetch remote content at render time`);
  }

  const unavailableText = HEADLINE_LINK_UNAVAILABLE;
  assert.ok(unavailableText.length > 0);

  console.log(
    `headline tests passed · ${checked} committed headlines modelled · ${withContext} carried a context line · ` +
      `${HEADLINE_CONTEXT_RULES.length} rules · ${topics.length} topics`,
  );
}

run();
